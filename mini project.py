def clear_content():
    for widget in content_area.winfo_children():
        widget.destroy()


def on_enter(e, widget, color):
    widget['background'] = color


def on_leave(e, widget, color):
    widget['background'] = color


def show_welcome():
    clear_content()
    Label(content_area, text="👋 ยินดีต้อนรับสู่ ศูนย์รวมความรู้ช่างมือโปร", font=("Arial Bold", 26), bg="white",
          fg="#1e293b").pack(pady=(100, 20))
    Label(content_area, text="MINT RAKVAISAI - TOOL GUIDE PRO", font=("Arial Bold", 16), bg="white", fg="#3b82f6").pack(
        pady=(0, 20))
    Label(content_area, text="กรุณาเลือกหมวดหมู่เครื่องมือจากแถบเมนูด้านบน เพื่อเริ่มศึกษาโครงสร้างและการใช้งาน",
          font=("Arial", 14), bg="white", fg="#64748b").pack()


def show_category(cat_name):
    clear_content()
    header_frame = Frame(content_area, bg="white")
    header_frame.pack(fill=X, pady=(10, 20))
    Label(header_frame, text=f"📂 {cat_name}", font=("Arial Bold", 22), bg="white", fg="#0f172a").pack(side=LEFT,
                                                                                                      padx=20)

    grid_frame = Frame(content_area, bg="white")
    grid_frame.pack(pady=10)

    col, row = 0, 0
    for tool_name in tool_data[cat_name].keys():
        btn_border = Frame(grid_frame, bg="#e2e8f0", padx=1, pady=1)
        btn_border.grid(row=row, column=col, padx=15, pady=10)
        btn = Button(btn_border, text=f"🔧 {tool_name}", font=("Arial Bold", 12),
                     width=25, pady=12, bg="#f8fafc", fg="#334155", relief="flat", cursor="hand2",
                     command=lambda t=tool_name, c=cat_name: show_detail(c, t))
        btn.pack()
        btn.bind("<Enter>", lambda e, b=btn: on_enter(e, b, "#e0f2fe"))
        btn.bind("<Leave>", lambda e, b=btn: on_leave(e, b, "#f8fafc"))
        col += 1
        if col > 2: col = 0; row += 1


def show_detail(cat, tool_name):
    global current_image
    clear_content()
    data = tool_data[cat][tool_name]

    top_bar = Frame(content_area, bg="white")
    top_bar.pack(fill=X, pady=(0, 15), padx=10)

    btn_back = Button(top_bar, text="◀ ย้อนกลับ", font=("Arial Bold", 12), bg="#ef4444", fg="white",
                      relief="flat", cursor="hand2", padx=15, pady=8, command=lambda: show_category(cat))
    btn_back.pack(side=LEFT)

    Label(top_bar, text=tool_name, font=("Arial Bold", 26), bg="white", fg="#0f172a").pack(side=LEFT, padx=30)

    body_frame = Frame(content_area, bg="white")
    body_frame.pack(fill=BOTH, expand=True, padx=10)

    left_frame = Frame(body_frame, bg="white", width=420)
    left_frame.pack(side=LEFT, fill=Y, padx=(0, 40))
    left_frame.pack_propagate(False)

    # --- ส่วนการดึงรูปภาพจากโฟลเดอร์ i ---
    img_filename = data["img"]
    img_path = os.path.join("i", img_filename)  # รวม Path เข้ากับโฟลเดอร์ i

    if HAS_PIL:
        try:
            if os.path.exists(img_path):
                img = Image.open(img_path)
                img.thumbnail((380, 380), RESAMPLE_METHOD)
                # สร้างพื้นหลังสีขาวขนาด 400x400 เพื่อให้รูปอยู่ตรงกลางสวยงาม
                new_img = Image.new("RGBA", (400, 400), "white")
                new_img.paste(img, ((400 - img.width) // 2, (400 - img.height) // 2))
                current_image = ImageTk.PhotoImage(new_img)
                img_label = Label(left_frame, image=current_image, bg="white", highlightbackground="#cbd5e1",
                                  highlightthickness=2)
                img_label.pack(pady=20)
            else:
                raise FileNotFoundError
        except Exception:
            Label(left_frame, text=f"[ ❌ ไม่พบไฟล์รูป ]\nตรวจสอบไฟล์ในโฟลเดอร์ i\nชื่อไฟล์: {img_filename}",
                  font=("Arial", 12), bg="#fef08a", fg="#b45309", width=35, height=15).pack(pady=20)
    else:
        Label(left_frame, text="[ ⚠️ ติดตั้ง Pillow ก่อน ]", font=("Arial", 12), bg="#fee2e2", fg="#991b1b",
              width=35, height=15).pack(pady=20)

    right_frame = Frame(body_frame, bg="white")
    right_frame.pack(side=LEFT, fill=BOTH, expand=True)

    def add_info_section(parent, icon_title, content, title_color, bg_color):
        sec_border = Frame(parent, bg=title_color, padx=3, pady=3)
        sec_border.pack(fill=X, pady=8)
        sec_inner = Frame(sec_border, bg=bg_color, padx=15, pady=12)
        sec_inner.pack(fill=BOTH, expand=True)
        Label(sec_inner, text=icon_title, font=("Arial Bold", 16), bg=bg_color, fg=title_color).pack(anchor="w")
        Label(sec_inner, text=content, font=("Arial", 13), bg=bg_color, fg="#1e293b", wraplength=550,
              justify=LEFT).pack(anchor="w", pady=(8, 0))

    add_info_section(right_frame, "📘 หน้าที่การใช้งาน", data["desc"], "#2563eb", "#eff6ff")
    add_info_section(right_frame, "🎯 เหมาะกับงานประเภทไหน", data["usage"], "#16a34a", "#f0fdf4")
    add_info_section(right_frame, "⚠️ ข้อควรระวัง", data["caution"], "#ea580c", "#fff7ed")
    add_info_section(right_frame, "✨ การดูแลรักษา (ทะนุถนอม)", data["care"], "#7c3aed", "#f5f3ff")


